"""Portable backup of everything that cannot be re-created by a fresh check:
the curated tables, the user's decisions (rejected / held / applied changeset items) and the FASTA files.

Bulk, re-downloadable data is left out: raw source payloads (`source_record`) and still-pending changeset
items. The archive uses '/' paths and UTF-8 only, so it restores on Windows, macOS and Linux alike."""
import json
import os
import sqlite3
import sys
import tempfile
import zipfile
from datetime import datetime
from pathlib import Path

from . import config, db

KEEP_TABLES = ["watchlist", "genome", "genome_sequence", "field_provenance", "genome_version", "changeset", "audit_log"]
VERSION = 1


def _compact_db(dest: Path) -> dict:
    """Write a compact copy of the live database to `dest` and return per-table row counts."""
    if dest.exists():
        dest.unlink()
    out = sqlite3.connect(dest)
    out.executescript(db.SCHEMA)
    db.migrate(out)
    out.execute("ATTACH DATABASE ? AS src", (str(config.DB_PATH),))
    counts = {}
    for t in KEEP_TABLES:
        cols = [r[1] for r in out.execute(f"PRAGMA main.table_info({t})")]
        have = {r[1] for r in out.execute(f"PRAGMA src.table_info({t})")}
        sel = ",".join(c if c in have else "NULL" for c in cols)
        out.execute(f"INSERT INTO main.{t}({','.join(cols)}) SELECT {sel} FROM src.{t}")
        counts[t] = out.execute(f"SELECT COUNT(*) FROM main.{t}").fetchone()[0]
    # Decisions matter (a rejected item must not come back); pending items are regenerated by the next check.
    cols = [r[1] for r in out.execute("PRAGMA main.table_info(changeset_item)")]
    out.execute(f"INSERT INTO main.changeset_item({','.join(cols)}) SELECT {','.join(cols)} FROM src.changeset_item "
                "WHERE decision IN ('rejected','hold','applied','approved')")
    counts["changeset_item"] = out.execute("SELECT COUNT(*) FROM main.changeset_item").fetchone()[0]
    out.commit()
    out.execute("DETACH DATABASE src")
    out.execute("VACUUM")
    out.close()
    return counts


def export_backup(dest: str | Path) -> dict:
    dest = Path(dest)
    dest.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        compact = Path(tmp) / "genomecurator.db"
        counts = _compact_db(compact)
        fasta = sorted((config.DATA_DIR / "genomes").rglob("*.fna")) if (config.DATA_DIR / "genomes").exists() else []
        with zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as z:
            z.write(compact, "genomecurator.db")
            for f in fasta:
                z.write(f, "genomes/" + f.relative_to(config.DATA_DIR / "genomes").as_posix())
            manifest = {"format": "genomecurator-backup", "version": VERSION, "created": datetime.now().isoformat(timespec="seconds"),
                        "platform": sys.platform, "tables": counts, "fasta_files": len(fasta)}
            z.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
    return {**manifest, "path": str(dest), "size_mb": round(dest.stat().st_size / 1e6, 1)}


def restore_backup(src: str | Path, force: bool = False) -> dict:
    """Restore into the current data folder. Refuses to replace an existing database unless force=True."""
    src = Path(src)
    with zipfile.ZipFile(src) as z:
        try:
            manifest = json.loads(z.read("manifest.json").decode("utf-8"))
        except KeyError:
            raise ValueError("backup manifest.json 이(가) 없습니다. GenomeCurator 백업 파일이 아닌 것 같습니다.") from None
        if manifest.get("format") != "genomecurator-backup":
            raise ValueError("GenomeCurator 백업 파일이 아닙니다.")
        if config.DB_PATH.exists() and not force:
            raise FileExistsError(f"{config.DB_PATH} 이(가) 이미 있습니다. 덮어쓰려면 --force (기존 데이터는 사라집니다).")
        config.DATA_DIR.mkdir(parents=True, exist_ok=True)
        root = (config.DATA_DIR / "genomes").resolve()
        for name in z.namelist():
            if name == "genomecurator.db":
                for suffix in ("", "-wal", "-shm"):
                    p = Path(str(config.DB_PATH) + suffix)
                    try:
                        if p.exists():
                            p.unlink()
                    except PermissionError:
                        raise RuntimeError("데이터베이스가 사용 중입니다. 실행 중인 GenomeCurator 앱을 종료한 뒤 다시 시도하세요.") from None
                with z.open(name) as fh, open(config.DB_PATH, "wb") as out:
                    out.write(fh.read())
            elif name.startswith("genomes/") and name.endswith(".fna"):
                target = (config.DATA_DIR / name).resolve()
                if root not in target.parents:  # never write outside data/genomes (zip-slip)
                    continue
                target.parent.mkdir(parents=True, exist_ok=True)
                with z.open(name) as fh, open(target, "wb") as out:
                    out.write(fh.read())
    con = db.connect()
    con.close()  # applies migrations for databases from older versions
    return manifest
